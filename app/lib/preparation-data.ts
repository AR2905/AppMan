export type PreparationCheckpoint = {
  id: string;
  label: string;
};

export type PreparationTopic = {
  id: string;
  title: string;
  checkpoints: PreparationCheckpoint[];
};

export type PreparationStack = {
  id: string;
  name: string;
  description?: string;
  topics: PreparationTopic[];
};

export type PreparationPriority = {
  level: string;
  topics: string;
};

export type PreparationTab = {
  id: string;
  name: string;
  tagline: string;
  note: string;
  priorities: PreparationPriority[];
  stacks: PreparationStack[];
};

type TopicInput = [title: string, labels: string[]];

function toTopic(stackId: string, index: number, [title, labels]: TopicInput): PreparationTopic {
  const id = `${stackId}-topic-${index + 1}`;

  return {
    id,
    title,
    checkpoints: labels.map((label, checkpointIndex) => ({
      id: `${id}-checkpoint-${checkpointIndex + 1}`,
      label,
    })),
  };
}

function groupedStack(
  id: string,
  name: string,
  entries: TopicInput[],
  description?: string,
): PreparationStack {
  return {
    id,
    name,
    description,
    topics: entries.map((entry, index) => toTopic(id, index, entry)),
  };
}

function simpleStack(
  id: string,
  name: string,
  labels: string[],
  description?: string,
): PreparationStack {
  return groupedStack(id, name, [["Checklist", labels]], description);
}

